def test_the_pd_document_prices_each_half_on_its_own_timeline():
    """P4 duty cycles and metrics per SYSTEM (P5.4). One evaluation shared
    between the halves would print a single measurement twice."""
    doc = json.loads(PD_ATLAS.read_text(encoding="utf-8"))
    chip_system = {chip["id"]: chip["system"] for chip in doc["chips"]}
    duty = {"sys.prefill": [], "sys.decode": []}
    for macro in doc["macros"]:
        value = macro.get("duty_cycle")
        if value is not None:
            duty[chip_system[macro["chip"]]].append(value)
    assert duty["sys.prefill"] and duty["sys.decode"]
    assert all(0.0 <= v <= 1.0 for values in duty.values() for v in values)
    # The two timelines are different machines, so their duty cycles differ.
    assert max(duty["sys.prefill"]) != max(duty["sys.decode"])
    keys = [metric["key"] for metric in doc["metrics"]]
    assert any(key.startswith("sys.prefill.") for key in keys)
    assert any(key.startswith("sys.decode.") for key in keys)
    # The headline label is published twice — once per system — which is exactly
    # why R28 requires every metric to name its system.
    headline = [m for m in doc["metrics"] if m["key"].endswith(".tokens_per_s")]
    assert len(headline) == 2
    assert headline[0]["label"] == headline[1]["label"]
    assert headline[0]["key"] != headline[1]["key"]


