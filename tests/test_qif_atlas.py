def test_self_test_corrupts_once_per_rule_and_every_refusal_fires(tmp_path):
    out = _run_core(
        """
        const rows = ATLAS.selfTest(doc);
        console.log(JSON.stringify({
          total: rows.length,
          cases: ATLAS.CORRUPTIONS.length,
          failed: rows.filter(r => !r.pass).map(r => r.rule + ' ' + r.what),
          skipped: rows.filter(r => r.skipped).map(r => r.rule + ' ' + r.what),
        }));
        """,
        tmp_path,
    )
    report = json.loads(out)
    assert report["failed"] == []
    # The clean document plus exactly one case per corruption.
    assert report["total"] == report["cases"] + 1
    # A skip is honest ("this document gives the harness no way to build that
    # corruption") but it proves nothing, so the set of them is PINNED: only the
    # two PD rules, which need a second system this one-system fixture has not
    # got. The PD document below fires exactly those.
    assert sorted(report["skipped"]) == [
        "R28 a metric in a two-system document says whose figure it is",
        "R29 a PD document loses the handoff that couples its two systems",
    ]


def test_the_shipped_documents_between_them_fire_every_corruption(tmp_path):
    """No rule may be skipped by EVERY document we ship.

    A corruption that is not constructible anywhere is a rule nothing exercises,
    which is how a refusal quietly stops working.
    """
    fired = set()
    total = None
    for document in (FIXTURE, PD_ATLAS):
        out = _run_core(
            """
            const rows = ATLAS.selfTest(doc);
            console.log(JSON.stringify({
              cases: ATLAS.CORRUPTIONS.length,
              fired: rows.filter(r => !r.skipped && r.rule !== 'R0').map(r => r.rule + ' ' + r.what),
              failed: rows.filter(r => !r.pass).map(r => r.rule + ' ' + r.what),
            }));
            """,
            tmp_path,
            document=document,
        )
        report = json.loads(out)
        assert report["failed"] == [], (document.name, report["failed"])
        fired.update(report["fired"])
        total = report["cases"]
    assert len(fired) == total, sorted(fired)


def test_every_rule_the_loader_can_emit_is_documented_in_schema_md(tmp_path):
    # The refusal panel tells the reader "See SCHEMA.md for the rule numbers",
    # so a rule id that fires but is undocumented sends the reader nowhere.
    out = _run_core(
        """
        console.log(JSON.stringify(Array.from(new Set(ATLAS.CORRUPTIONS.map(c => c.rule))).sort()));
        """,
        tmp_path,
    )
    rules = json.loads(out)
    html = _html()
    emitted = set(re.findall(r'[EW]\("(R\d+)"', html))
    assert emitted <= set(rules), sorted(emitted - set(rules))
    schema = SCHEMA_MD.read_text(encoding="utf-8")
    documented = set(re.findall(r"^\| (\d+) \|", schema, re.MULTILINE))
    missing = sorted(int(r[1:]) for r in emitted if r[1:] not in documented)
    assert not missing, "rules missing from SCHEMA.md: %s" % missing


def test_schema_md_states_the_self_tests_real_case_count(tmp_path):
    """WAVE C AUDIT: SCHEMA.md said 34 cases while the harness ran 37.

    SCHEMA.md is the frozen fws_atlas/1 contract and the copy a reader trusts,
    and the rule-coverage test above never checked the COUNT -- only that each
    rule id appears in the table. This asserts the integer in the prose equals
    what selfTest actually returns, so the sentence cannot rot again.
    """
    out = _run_core("console.log(ATLAS.selfTest(doc).length);", tmp_path)
    rows = int(out)
    schema = SCHEMA_MD.read_text(encoding="utf-8")
    stated = re.search(r"It runs (\d+)\s*\ncases:", schema)
    assert stated, "SCHEMA.md no longer states a self-test case count"
    assert int(stated.group(1)) == rows


