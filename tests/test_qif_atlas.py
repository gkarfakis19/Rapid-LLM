def _shipped_documents():
    """Every fws_atlas/1 document in docs/qif/atlas/, found by SCHEMA ID.

    WAVE C AUDIT: this was a hand-maintained tuple, and qwen3_5_4b.json shipped
    into the same directory without being added to it -- so the view-rule sweep
    and the D23 scan below, which both claim to cover "every shipped document",
    silently skipped one. Globbing by the schema id means a document another
    workstream lands is covered the moment it exists, with nobody to remember.
    """
    found = []
    for path in sorted(ATLAS_DIR.glob("*.json")):
        try:
            blob = json.loads(path.read_text(encoding="utf-8"))
        except (ValueError, UnicodeDecodeError):
            continue
        if isinstance(blob, dict) and blob.get("schema") == "fws_atlas/1":
            found.append(path.name)
    return tuple(found)


