"""QIF P5 system-atlas tests.

The atlas is one self-contained HTML file with an embedded copy of the
fixture, so three things can rot silently between suite runs: the embedded
blob can drift from the sibling fixture, the fixture can stop conforming to
the frozen fws_atlas/1 schema, and the loader can pick up a JavaScript syntax
error that renders the page blank. The suite catches all three.

The loader tests shell out to node (skipped when node is absent, the
tests/test_webui_browser.py precedent) and evaluate only the block between
the ATLAS-CORE markers, which carries no DOM.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import textwrap
from pathlib import Path

import pytest


PROJECT_ROOT = Path(__file__).resolve().parents[1]
ATLAS_DIR = PROJECT_ROOT / "docs" / "qif" / "atlas"
ATLAS_HTML = ATLAS_DIR / "atlas.html"
FIXTURE = ATLAS_DIR / "fixture_llama7b_tp2.json"
PD_ATLAS = ATLAS_DIR / "pd_llama7b.json"
SCHEMA_MD = ATLAS_DIR / "SCHEMA.md"

# The PD pair the shipped document is (P5.4, D16). It is generated by the same
# command its provenance block prints, so the regenerate-and-compare test below
# and the file itself can never drift apart silently.
PD_ARGS = dict(
    # Absolute, so the test does not depend on the caller's working directory.
    # The tool prints the repo-relative spelling back into provenance, so the
    # emitted bytes are the same either way.
    hardware_config=str(PROJECT_ROOT / "configs/hardware-config/fws_cim_llama7b_mapped.yaml"),
    model_config=str(PROJECT_ROOT / "configs/model-config/llama2_7b_fws_inf.yaml"),
    prefill_layers_per_chip=8,
    decode_layers_per_chip=4,
    prefill_shared_chiplets=2,
    decode_shared_chiplets=1,
    decode_window=4,
    priced=True,
    label="Llama2-7B",
)

CORE_START = "// ==ATLAS-CORE-START=="
CORE_END = "// ==ATLAS-CORE-END=="
EMBED_RE = re.compile(
    r'<script[^>]*type="application/json"[^>]*id="atlas-embedded"[^>]*>(.*?)</script>',
    re.DOTALL,
)


def _html() -> str:
    return ATLAS_HTML.read_text(encoding="utf-8")


def _fixture() -> dict:
    return json.loads(FIXTURE.read_text(encoding="utf-8"))


def _node() -> str:
    node = shutil.which("node")
    if node is None:
        pytest.skip("node is not installed; the atlas loader tests need it")
    return node


def _run_core(driver: str, tmp_path: Path, document: Path = FIXTURE) -> str:
    """Evaluate the ATLAS core block headlessly and run a driver against it.

    ``document`` defaults to the P5 fixture; P3's export tests pass their own
    emitted document so the SAME loader judges both (tests/test_qif_mapping.py).
    """
    html = _html()
    core = html[html.index(CORE_START) : html.index(CORE_END)]
    script = tmp_path / "driver.js"
    script.write_text(
        "const fs = require('fs');\n"
        "const doc = JSON.parse(fs.readFileSync(%r, 'utf8'));\n" % str(document)
        + "const ATLAS = eval('(function(){' + "
        + json.dumps(core)
        + " + '; return ATLAS; })()');\n"
        + textwrap.dedent(driver),
        encoding="utf-8",
    )
    result = subprocess.run(
        [_node(), str(script)],
        capture_output=True,
        text=True,
        timeout=120,
        cwd=str(PROJECT_ROOT),
    )
    assert result.returncode == 0, result.stderr
    return result.stdout.strip()


